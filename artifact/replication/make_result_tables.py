#!/usr/bin/env python3
"""
make_result_tables.py

Turn benchmark runs into the two LaTeX tables the revised manuscript needs:

    tables/table_current_models.tex   validation of the task on newer models
    tables/table_hallucination.tex    the controlled probe measurements

Both tables are generated from the run files rather than transcribed, so the
manuscript cannot drift from the measurements.

Runs are discovered by their filename tag, which run_benchmark.py writes as
    <provider>_<model>_<tag>_<timestamp>.jsonl
with tags: base, null, inject, shuffle, rep.

Usage
-----
    python3 make_result_tables.py --runs runs --out ../../manuscript/tables
"""

from __future__ import annotations

import argparse
import json
import math
import pathlib
import re
from collections import Counter, defaultdict

TAGS = ("base", "null", "inject", "shuffle", "rep")


# --------------------------------------------------------------------------
def mcc(tp, fp, fn, tn):
    den = math.sqrt((tp + fp) * (tp + fn) * (tn + fp) * (tn + fn))
    return None if den == 0 else (tp * tn - fp * fn) / den


def score(pairs):
    tp = sum(1 for y, p in pairs if y == 1 and p == 1)
    fp = sum(1 for y, p in pairs if y == 0 and p == 1)
    fn = sum(1 for y, p in pairs if y == 1 and p == 0)
    tn = sum(1 for y, p in pairs if y == 0 and p == 0)
    n = len(pairs)
    pos, neg = tp + fn, fp + tn
    P = tp / (tp + fp) if (tp + fp) else None
    R = tp / pos if pos else None
    F1 = 2 * P * R / (P + R) if (P and R) else (0.0 if P is not None and R is not None else None)
    A = (tp + tn) / n if n else None
    S = tn / neg if neg else None
    B = 0.5 * (R + S) if (R is not None and S is not None) else None
    prev = pos / n if n else None
    base = max(prev, 1 - prev) if prev is not None else None
    return {
        "n": n, "TP": tp, "FP": fp, "FN": fn, "TN": tn,
        "P": P, "R": R, "F1": F1, "A": A, "spec": S, "bal": B,
        "MCC": mcc(tp, fp, fn, tn), "prev": prev, "baseline": base,
        "dA": None if (A is None or base is None) else A - base,
    }


def load_runs(run_dir: pathlib.Path) -> dict[str, dict[str, list[dict]]]:
    """Return {model_label: {tag: records}}."""
    out: dict[str, dict[str, list[dict]]] = defaultdict(dict)
    for path in sorted(run_dir.glob("*.jsonl")):
        m = re.match(r"(.+?)_(" + "|".join(TAGS) + r")_\d{8}T\d{6}Z\.jsonl$", path.name)
        if not m:
            continue
        tag = m.group(2)
        recs = [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
        if not recs:
            continue
        label = recs[0].get("resolved_model") or recs[0].get("model_requested") or m.group(1)
        out[label][tag] = recs
    return out


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def esc(s: str) -> str:
    return str(s).replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


# --------------------------------------------------------------------------
def build_performance_table(runs) -> str:
    rows = []
    for label, tags in sorted(runs.items()):
        base = tags.get("base")
        if not base:
            continue
        base = [r for r in base if r.get("repeat", 0) == 0]
        n_calls = len(base)
        usable = [r for r in base if not r.get("api_error")]
        parse_rate = (
            sum(1 for r in usable if r.get("parse_ok")) / len(usable) if usable else None
        )
        # Under constrained decoding the parse rate is 1.0 by construction and
        # says nothing about the model, so it is reported as a dagger instead.
        constrained = any(r.get("json_mode") for r in usable)
        for target in ("incorrect", "incomplete"):
            pairs = [
                (int(r[f"y_{target}"]), int(r[target]))
                for r in usable
                if r.get("parse_ok") and r.get(f"y_{target}") is not None
                and r.get(target) is not None
            ]
            if pairs:
                rows.append((label, target, score(pairs), parse_rate,
                             n_calls, constrained))

    if not rows:
        return ""

    out = [
        r"% Auto-generated by artifact/replication/make_result_tables.py",
        r"\begin{table*}[ht!]",
        r"    \centering",
        r"    \caption{Validation of the task on the DataGuard 300-app evaluation "
        r"set, whose class prior is near balanced (0.54 \textit{Incorrect}, 0.58 "
        r"\textit{Incomplete}) rather than the 0.913/0.807 of the original test "
        r"set. All models are evaluated zero-shot with the same prompt. "
        r"$\Delta$A is accuracy minus the best constant classifier; "
        r"\textit{Parse} is the share of responses conforming to the requested "
        r"JSON schema. $\dagger$ marks a run under constrained JSON decoding, "
        r"which guarantees syntactically valid JSON but not the requested keys, "
        r"so its parse rate is not comparable with the unconstrained runs.}",
        r"    \label{tab:current_models}",
        r"    \resizebox{\textwidth}{!}{%",
        r"    \begin{tabular}{|l|l|c|c|c|c|c|c|c|c|c|}",
        r"        \hline",
        r"        \textbf{Model} & \textbf{Category} & \textbf{P} & \textbf{R} & "
        r"\textbf{F1} & \textbf{A} & $\mathbf{\Delta}$\textbf{A} & \textbf{Spec.} "
        r"& \textbf{Bal.A} & \textbf{MCC} & \textbf{Parse} \\",
        r"        \hline",
    ]
    last = None
    for label, target, s, parse_rate, _n, constrained in rows:
        shown = esc(label) if label != last else ""
        last = label
        out.append(
            f"        {shown} & {target.capitalize()} & {f3(s['P'])} & {f3(s['R'])} & "
            f"{f3(s['F1'])} & {f3(s['A'])} & {f3(s['dA'])} & {f3(s['spec'])} & "
            f"{f3(s['bal'])} & {f3(s['MCC'])} & "
            f"{f3(parse_rate)}{r'$^\dagger$' if constrained else ''} \\\\"
        )
        out.append(r"        \hline")
    out += [r"    \end{tabular}", r"    }", r"\end{table*}"]
    return "\n".join(out) + "\n"


def build_hallucination_table(runs) -> str:
    rows = []
    for label, tags in sorted(runs.items()):
        entry = {"label": label}

        # Format compliance, measured on the unperturbed run.
        base = [r for r in tags.get("base", []) if r.get("repeat", 0) == 0]
        usable = [r for r in base if not r.get("api_error")]
        if usable:
            entry["constrained"] = any(r.get("json_mode") for r in usable)
            entry["format_violation"] = sum(
                1 for r in usable if not r.get("parse_ok")
            ) / len(usable)
            entry["deviation"] = sum(
                1 for r in usable if r.get("failure_mode")
            ) / len(usable)

        # Null probe: reference incorrect = 0, so a 1 asserts absent content.
        nul = [r for r in tags.get("null", []) if not r.get("api_error") and r.get("incorrect") is not None]
        if nul:
            entry["unsupported"] = sum(1 for r in nul if int(r["incorrect"]) != 0) / len(nul)
            entry["n_null"] = len(nul)

        # Inject probe: reference incorrect = 1, so a 0 ignores the evidence.
        inj = [r for r in tags.get("inject", []) if not r.get("api_error") and r.get("incorrect") is not None]
        if inj:
            entry["grounding"] = sum(1 for r in inj if int(r["incorrect"]) != 1) / len(inj)
            entry["n_inject"] = len(inj)

        # Sentence-order probe: any flip is instability.
        shuf = tags.get("shuffle", [])
        if shuf and base:
            b = {r["app_id"]: r for r in base if r.get("parse_ok")}
            s = {r["app_id"]: r for r in shuf if r.get("parse_ok") and not r.get("api_error")}
            common = set(b) & set(s)
            for target in ("incorrect", "incomplete"):
                flips = sum(
                    1 for a in common
                    if b[a].get(target) is not None and s[a].get(target) is not None
                    and int(b[a][target]) != int(s[a][target])
                )
                n = sum(
                    1 for a in common
                    if b[a].get(target) is not None and s[a].get(target) is not None
                )
                entry[f"order_{target}"] = flips / n if n else None

        # Repeated identical calls.
        rep = tags.get("rep", [])
        if rep:
            by_app = defaultdict(list)
            for r in rep:
                if r.get("parse_ok") and not r.get("api_error"):
                    by_app[r["app_id"]].append(r)
            multi = {k: v for k, v in by_app.items() if len(v) >= 2}
            for target in ("incorrect", "incomplete"):
                unstable = sum(
                    1 for v in multi.values()
                    if len({r[target] for r in v if r.get(target) is not None}) > 1
                )
                entry[f"repeat_{target}"] = unstable / len(multi) if multi else None
            entry["n_repeat_apps"] = len(multi)

        rows.append(entry)

    if not rows:
        return ""

    out = [
        r"% Auto-generated by artifact/replication/make_result_tables.py",
        r"\begin{table*}[ht!]",
        r"    \centering",
        r"    \caption{Direct measurement of hallucination and instability, "
        r"replacing the inference from metric variation used in the submitted "
        r"version. \textit{Format} is the share of responses violating the "
        r"requested schema. \textit{Unsupported} is the share of null-probe "
        r"responses asserting a discrepancy when the privacy policy shown to the "
        r"model contained no data-practice statement at all (reference answer 0). "
        r"\textit{Grounding} is the share of injection-probe responses failing to "
        r"flag an explicitly added undeclared disclosure (reference answer 1). "
        r"\textit{Order} and \textit{Repeat} are label-change rates under a "
        r"meaning-preserving sentence reordering and under identical repeated "
        r"calls. For every column, lower is better.}",
        r"    \label{tab:hallucination}",
        r"    \resizebox{\textwidth}{!}{%",
        r"    \begin{tabular}{|l|c|c|c|c|c|c|c|}",
        r"        \hline",
        r"        \multirow{2}{*}{\textbf{Model}} & \multirow{2}{*}{\textbf{Format}} "
        r"& \multirow{2}{*}{\textbf{Unsupported}} & \multirow{2}{*}{\textbf{Grounding}} "
        r"& \multicolumn{2}{c|}{\textbf{Order flip}} & "
        r"\multicolumn{2}{c|}{\textbf{Repeat flip}} \\",
        r"        \cline{5-8}",
        r"        & & & & \textit{Incorr.} & \textit{Incompl.} & \textit{Incorr.} "
        r"& \textit{Incompl.} \\",
        r"        \hline",
    ]
    for e in rows:
        out.append(
            f"        {esc(e['label'])} & "
            f"{f3(e.get('format_violation'))}"
            f"{r'$^\dagger$' if e.get('constrained') else ''} & "
            f"{f3(e.get('unsupported'))} & {f3(e.get('grounding'))} & "
            f"{f3(e.get('order_incorrect'))} & {f3(e.get('order_incomplete'))} & "
            f"{f3(e.get('repeat_incorrect'))} & {f3(e.get('repeat_incomplete'))} \\\\"
        )
        out.append(r"        \hline")
    out += [r"    \end{tabular}", r"    }", r"\end{table*}"]
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=pathlib.Path, default=pathlib.Path("runs"))
    ap.add_argument("--out", type=pathlib.Path, required=True)
    ap.add_argument("--summary", type=pathlib.Path, default=None)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    runs = load_runs(args.runs)
    if not runs:
        raise SystemExit(f"No run files found in {args.runs}")

    print("Models found:")
    for label, tags in runs.items():
        print(f"  {label}: {', '.join(sorted(tags))}")

    perf = build_performance_table(runs)
    hall = build_hallucination_table(runs)

    if perf:
        (args.out / "table_current_models.tex").write_text(perf, encoding="utf-8")
        print(f"Wrote {args.out/'table_current_models.tex'}")
    if hall:
        (args.out / "table_hallucination.tex").write_text(hall, encoding="utf-8")
        print(f"Wrote {args.out/'table_hallucination.tex'}")

    if args.summary:
        summary = {}
        for label, tags in runs.items():
            base = [r for r in tags.get("base", []) if r.get("repeat", 0) == 0]
            usable = [r for r in base if not r.get("api_error")]
            s = {}
            for target in ("incorrect", "incomplete"):
                pairs = [
                    (int(r[f"y_{target}"]), int(r[target]))
                    for r in usable
                    if r.get("parse_ok") and r.get(f"y_{target}") is not None
                    and r.get(target) is not None
                ]
                if pairs:
                    s[target] = {k: (round(v, 4) if isinstance(v, float) else v)
                                 for k, v in score(pairs).items()}
            summary[label] = {
                "targets": s,
                "tags_present": sorted(tags),
                "failure_modes": dict(
                    Counter(r.get("failure_mode") for r in usable if r.get("failure_mode"))
                ),
            }
        args.summary.write_text(json.dumps(summary, indent=2), encoding="utf-8")
        print(f"Wrote {args.summary}")


if __name__ == "__main__":
    main()
